package gen

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/fixkme/protoc-gen-gom/internal/pbext"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"
)

var (
	errsPackage = protogen.GoImportPath("github.com/fixkme/gokit/errs")
)

type CodeErrorFile struct {
	PackageName string
	Enums       map[string]*protogen.Enum
}
type CodeErrorGenerator struct {
	*protogen.Plugin
	CodeErrorFiles map[string]*CodeErrorFile
	GenerateFiles  map[string]*protogen.GeneratedFile
}

func NewCodeErrorGenerator(plugin *protogen.Plugin) *CodeErrorGenerator {
	return &CodeErrorGenerator{
		Plugin:         plugin,
		CodeErrorFiles: make(map[string]*CodeErrorFile),
		GenerateFiles:  make(map[string]*protogen.GeneratedFile),
	}
}

func (e *CodeErrorGenerator) collectErrorEnum(f *protogen.File) error {
	for _, enum := range f.Enums {
		e.addEnum(f, enum)
	}
	return nil
}

func (e *CodeErrorGenerator) addEnum(f *protogen.File, enum *protogen.Enum) error {
	var isCodeError bool
	hasExtension := proto.HasExtension(enum.Desc.Options(), pbext.E_IsCodeError)
	if hasExtension {
		if v, ok := proto.GetExtension(enum.Desc.Options(), pbext.E_IsCodeError).(bool); ok && v {
			isCodeError = true
		}
	}
	isCodeError = isCodeError || strings.Contains(enum.Comments.Leading.String(), "@CodeError")
	if !isCodeError {
		return nil
	}
	enumName := enum.GoIdent.GoName
	pkgName := string(f.GoPackageName)
	codeErrorFile, ex := e.CodeErrorFiles[pkgName]
	if !ex {
		codeErrorFile = &CodeErrorFile{
			PackageName: pkgName,
			Enums:       make(map[string]*protogen.Enum),
		}
		e.CodeErrorFiles[pkgName] = codeErrorFile
		geneFileName := e.getGenerateFileName(pkgName, f)
		e.GenerateFiles[pkgName] = e.Plugin.NewGeneratedFile(geneFileName, protogen.GoImportPath(pkgName))
	}
	codeErrorFile.Enums[enumName] = enum
	return nil
}

func (e *CodeErrorGenerator) getGenerateFileName(pkgName string, f *protogen.File) string {
	idx := strings.LastIndex(f.GeneratedFilenamePrefix, "/")
	if idx > 0 {
		return f.GeneratedFilenamePrefix[:idx+1] + pkgName + ".err.go"
	}
	fname := fmt.Sprintf("%s/%s%s", pkgName, pkgName, ".err.go")
	return fname
}

func (e *CodeErrorGenerator) GenerateFile() error {
	// 收集rpc message
	for _, f := range e.Plugin.Files {
		if f.Generate {
			e.collectErrorEnum(f)
		}
	}
	// 生成代码
	for pkgName, f := range e.CodeErrorFiles {
		e.GenerateCodeErrorFile(pkgName, f)
	}
	return nil
}

func (e *CodeErrorGenerator) GenerateCodeErrorFile(pkgName string, file *CodeErrorFile) {
	g := e.GenerateFiles[pkgName]

	g.P("// Code generated by protoc-gen-gom. DO NOT EDIT.")
	g.P("package ", file.PackageName)
	g.P()

	for _, enum := range file.Enums {
		e.generateCodeError(g, enum)
	}

}

func (e *CodeErrorGenerator) generateCodeError(g *protogen.GeneratedFile, enum *protogen.Enum) {
	g.P(enum.Comments.Leading, "var (")
	for _, v := range enum.Values {
		g.P(e.leadingComment(v), toPascalCase(string(v.Desc.Name())), " = ",
			errsPackage.Ident("CreateCodeError"), "(int32(", v.GoIdent.GoName, "), ", strconv.Quote(string(v.Desc.Name())), ")")
	}
	g.P(")")
	g.P()
}

func (e *CodeErrorGenerator) leadingComment(v *protogen.EnumValue) protogen.Comments {
	leadingComments := appendDeprecationSuffix(v.Comments.Leading,
		v.Desc.ParentFile(),
		v.Desc.Options().(*descriptorpb.EnumValueOptions).GetDeprecated())
	commonts := leadingComments
	if trailingComment := trailingComment(v.Comments.Trailing); trailingComment != "" {
		commonts += protogen.Comments(trailingComment)
	}
	return commonts
}
