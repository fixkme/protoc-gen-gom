package gen

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
)

const (
	contextPackage = protogen.GoImportPath("context")
	rpcPackage     = protogen.GoImportPath("github.com/fixkme/gokit/rpc")
	protoPackage   = protogen.GoImportPath("google.golang.org/protobuf/proto")
	grpcPackage    = protogen.GoImportPath("google.golang.org/grpc")
)

type RpcFile struct {
	ServiceName string
	PackageName string
	Messages    map[string]*protogen.Message
	Methods     map[string]*[2]string
	MethodSort  []string
}

type RpcGenerator struct {
	*protogen.Plugin
	RpcFiles      map[string]*RpcFile
	GenerateFiles map[string]*protogen.GeneratedFile
}

func NewRpcGenerator(plugin *protogen.Plugin) *RpcGenerator {
	return &RpcGenerator{
		Plugin:        plugin,
		RpcFiles:      make(map[string]*RpcFile),
		GenerateFiles: make(map[string]*protogen.GeneratedFile),
	}
}

func (r *RpcGenerator) collectCSMessage(f *protogen.File) error {
	for _, message := range f.Messages {
		r.addMessage(f, message)
	}
	return nil
}

func (r *RpcGenerator) addMessage(f *protogen.File, message *protogen.Message) error {
	msgName := message.GoIdent.GoName
	if !(msgName[0] == 'C' || msgName[0] == 'S') {
		return nil
	}
	methodName := msgName[1:]
	pkgName := string(f.GoPackageName)
	rpcFile, ex := r.RpcFiles[pkgName]
	if !ex {
		rpcFile = &RpcFile{
			PackageName: pkgName,
			ServiceName: capitalize(pkgName),
			Messages:    make(map[string]*protogen.Message),
			Methods:     make(map[string]*[2]string),
		}
		r.RpcFiles[pkgName] = rpcFile
		geneFileName := r.getGenerateFileName(pkgName, f)
		r.GenerateFiles[pkgName] = r.Plugin.NewGeneratedFile(geneFileName, protogen.GoImportPath(pkgName))
	}
	rpcFile.Messages[msgName] = message
	v2, ok := rpcFile.Methods[methodName]
	if !ok {
		v2 = &[2]string{"", ""}
		rpcFile.Methods[methodName] = v2
	}
	if msgName[0] == 'C' {
		v2[0] = msgName
	} else if msgName[0] == 'S' {
		v2[1] = msgName
	}
	return nil
}

func (r *RpcGenerator) getGenerateFileName(pkgName string, f *protogen.File) string {
	idx := strings.LastIndex(f.GeneratedFilenamePrefix, "/")
	if idx > 0 {
		return f.GeneratedFilenamePrefix[:idx+1] + pkgName + ".rpc.go"
	}
	fname := fmt.Sprintf("%s/%s%s", pkgName, pkgName, ".rpc.go")
	return fname
}

func (r *RpcGenerator) GenerateFile(rpcFiles map[string]struct{}) error {
	// 收集rpc message
	for _, f := range r.Plugin.Files {
		if f.Generate {
			pkgName := string(f.GoPackageName)
			if _, ok := rpcFiles[pkgName]; ok {
				r.collectCSMessage(f)
			}
		}
	}
	// 检查
	for _, f := range r.RpcFiles {
		f.MethodSort = make([]string, 0, len(f.Methods))
		for method, v2 := range f.Methods {
			if len(v2[0]) == 0 {
				return fmt.Errorf("rpc method %s not exist request", method)
			} else if len(v2[1]) == 0 {
				return fmt.Errorf("rpc method %s not exist response", method)
			}
			f.MethodSort = append(f.MethodSort, method)
		}
		sort.Strings(f.MethodSort)
	}
	// 生成代码
	for pkgName, f := range r.RpcFiles {
		r.GenerateRpcFile(pkgName, f)
	}
	return nil
}

func (r *RpcGenerator) GenerateRpcFile(pkgName string, file *RpcFile) {
	g := r.GenerateFiles[pkgName]

	g.P("// Code generated by protoc-gen-gom. DO NOT EDIT.")
	g.P("package ", file.PackageName)
	g.P()

	r.generateService(g, file)

	r.generateMethodHandler(g, file)

	r.generateServiceDesc(g, file)
}

func (r *RpcGenerator) generateService(g *protogen.GeneratedFile, file *RpcFile) {
	g.P("type ", file.ServiceName, "Server interface {")
	for _, method := range file.MethodSort {
		v2 := file.Methods[method]
		g.P(method, "(", contextPackage.Ident("Context"), ", *", v2[0], ") (*", v2[1], ", error)")
	}
	g.P("}")
	g.P()

	g.P("func Register", file.ServiceName, "Server(s ", rpcPackage.Ident("ServiceRegistrar"), ", srv ", file.ServiceName, "Server) {")
	g.P("s.RegisterService(&", file.ServiceName, "_ServiceDesc, srv)")
	g.P("}")
	g.P()
}

func (r *RpcGenerator) generateMethodHandler(g *protogen.GeneratedFile, file *RpcFile) {
	for _, method := range file.MethodSort {
		v2 := file.Methods[method]
		g.P("func _", file.ServiceName, "_", method, "_Handler(srv any, ctx ", contextPackage.Ident("Context"),
			", dec func(", protoPackage.Ident("Message"), ") error) (", protoPackage.Ident("Message"), ", error) {")
		g.P("req := new(", v2[0], ")")
		g.P("if err := dec(req); err != nil {")
		g.P("return nil, err")
		g.P("}")
		g.P("return srv.(", file.ServiceName, "Server).", method, "(ctx, req)")
		g.P("}")
		g.P()
	}
}

func (r *RpcGenerator) generateServiceDesc(g *protogen.GeneratedFile, file *RpcFile) {
	g.P("var ", file.ServiceName, "_ServiceDesc = ", rpcPackage.Ident("ServiceDesc"), "{")
	g.P("ServiceName: ", strconv.Quote(file.ServiceName), ",")
	g.P("HandlerType: (*", file.ServiceName, "Server)(nil),")
	g.P("Methods: []", rpcPackage.Ident("MethodDesc"), "{")
	for _, method := range file.MethodSort {
		g.P("{")
		g.P("MethodName: ", strconv.Quote(method), ",")
		g.P("Handler: ", "_", file.ServiceName, "_", method, "_Handler,")
		g.P("},")
	}
	g.P("},")
	g.P("}")
	g.P()
}
